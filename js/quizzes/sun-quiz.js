/* =========================================
   VARIABLES
========================================= */

let currentQuestion = 0;

let score = 0;
let submittedAnswers = [];
let attemptId = crypto.randomUUID();

let answered = false;


/* =========================================
   SHUFFLE
========================================= */

function shuffleAnswers(question) {

    const answerObjects =
        question.answers.map(
            (answer, index) => {

                return {

                    text: answer, originalIndex: index,

                    correct:
                        index === question.correct

                };

            }
        );


    for (
        let i = answerObjects.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() * (i + 1)
            );


        [
            answerObjects[i],
            answerObjects[j]
        ] =
        [
            answerObjects[j],
            answerObjects[i]
        ];

    }


    return answerObjects;
}


/* =========================================
   LOAD QUESTION
========================================= */

function loadQuestion() {

    answered = false;


    const q =
        questions[currentQuestion];


    document.getElementById(
        "questionNumber"
    ).textContent =
        `QUESTION ${
            String(currentQuestion + 1)
            .padStart(2,"0")
        } / ${questions.length}`;


    document.getElementById(
        "difficulty"
    ).textContent =
        q.difficulty;


    document.getElementById(
        "question"
    ).textContent =
        q.question;


    /* FULL PROGRESS INCLUDING CURRENT QUESTION */

    document.getElementById(
        "progressBar"
    ).style.width =
        `${(
            (currentQuestion + 1) /
            questions.length
        ) * 100}%`;


    const answersContainer =
        document.getElementById(
            "answers"
        );


    answersContainer.innerHTML = "";


    const shuffled =
        shuffleAnswers(q);


    shuffled.forEach(
        answerObject => {

            const button =
                document.createElement(
                    "button"
                );


            button.className =
                "answer";


            button.textContent =
                answerObject.text;


            button.dataset.correct = answerObject.correct;
            button.dataset.originalIndex = answerObject.originalIndex;


            button.onclick =
                function() {

                    selectAnswer(
                        answerObject.correct,
                        button
                    );

                };


            answersContainer.appendChild(
                button
            );

        }
    );


    document.getElementById(
        "nextButton"
    ).style.display =
        "none";
}


/* =========================================
   ANSWER
========================================= */

function selectAnswer(
    isCorrect,
    selectedButton
) {

    if (answered)
        return;


    answered = true;
    submittedAnswers[currentQuestion] = Number(selectedButton.dataset.originalIndex);


    const buttons =
        document.querySelectorAll(
            ".answer"
        );


    buttons.forEach(
        button => {

            button.classList.add(
                "disabled"
            );

        }
    );


    if (isCorrect) {

        selectedButton.classList.add(
            "correct"
        );

        score++;

    }

    else {

        selectedButton.classList.add(
            "wrong"
        );


        buttons.forEach(
            button => {

                if (
                    button.dataset.correct
                    === "true"
                ) {

                    button.classList.add(
                        "correct"
                    );

                }

            }
        );

    }


    document.getElementById(
        "nextButton"
    ).style.display =
        "inline-flex";
}


/* =========================================
   NEXT QUESTION
========================================= */

function nextQuestion() {

    currentQuestion++;


    if (
        currentQuestion >=
        questions.length
    ) {

        showResult();

        return;

    }


    loadQuestion();
}


