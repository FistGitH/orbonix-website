/* =========================================================
   NORMALIZE
========================================================= */

function normalizeSearchText(text) {

    return String(text || "")
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .replace(/[^a-z0-9\s]/g, " ")
        .replace(/\s+/g, " ")
        .trim();

}


/* =========================================================
   FUZZY MATCH
========================================================= */

function levenshtein(a, b) {

    if (a === b) return 0;

    if (!a.length) return b.length;

    if (!b.length) return a.length;

    const matrix = [];

    for (let i = 0; i <= b.length; i++) {
        matrix[i] = [i];
    }

    for (let j = 0; j <= a.length; j++) {
        matrix[0][j] = j;
    }

    for (let i = 1; i <= b.length; i++) {

        for (let j = 1; j <= a.length; j++) {

            if (b[j - 1] === a[j - 1]) {

                matrix[i][j] =
                    matrix[i - 1][j - 1];

            } else {

                matrix[i][j] = Math.min(
                    matrix[i - 1][j] + 1,
                    matrix[i][j - 1] + 1,
                    matrix[i - 1][j - 1] + 1
                );

            }

        }

    }

    return matrix[b.length][a.length];

}


/* =========================================================
   SCORE
========================================================= */

function scoreSearchResult(page, query) {

    const q = normalizeSearchText(query);

    if (!q) return 0;

    const words = q.split(" ");

    const title =
        normalizeSearchText(page.title);

    const category =
        normalizeSearchText(page.category);

    const keywords =
        normalizeSearchText(page.keywords);

    const description =
        normalizeSearchText(page.description);

    let score = 0;


    /* Exact title */

    if (title === q) {
        score += 2000;
    }


    /* Title */

    if (title.includes(q)) {
        score += 1000;
    }


    /* Category */

    if (category.includes(q)) {
        score += 500;
    }


    /* Keywords */

    if (keywords.includes(q)) {
        score += 700;
    }


    /* Description */

    if (description.includes(q)) {
        score += 200;
    }


    /* Individual words */

    for (const word of words) {

        if (word.length < 2) continue;


        if (title.includes(word)) {
            score += 400;
        }


        if (category.includes(word)) {
            score += 200;
        }


        if (keywords.includes(word)) {
            score += 250;
        }


        if (description.includes(word)) {
            score += 100;
        }

    }


    /* Small spelling mistakes */

    const titleWords =
        title.split(" ");

    for (const word of words) {

        if (word.length < 4) continue;

        for (const titleWord of titleWords) {

            if (titleWord.length < 4) continue;

            const distance =
                levenshtein(
                    word,
                    titleWord
                );

            if (distance === 1) {
                score += 150;
            }

            if (
                distance === 2 &&
                word.length >= 6
            ) {
                score += 75;
            }

        }

    }


    return score;

}


/* =========================================================
   SEARCH
========================================================= */

function searchOrbonix(query) {

    const normalized =
        normalizeSearchText(query);

    if (!normalized) {
        return [];
    }


    return ORBONIX_PAGES

        .map(page => ({

            ...page,

            score:
                scoreSearchResult(
                    page,
                    normalized
                )

        }))

        .filter(page =>
            page.score > 0
        )

        .sort((a, b) =>
            b.score - a.score
        )

        .slice(0, 12);

}


