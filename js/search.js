/* =========================================================
   NORMALIZE TEXT
========================================================= */

function normalizeSearchText(text) {

    return String(text || "")
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .replace(/[^a-z0-9\s]/g, " ")
        .replace(/\s+/g, " ")
        .trim();

}


/* =========================================================
   LEVENSHTEIN DISTANCE
   Allows small typing mistakes.
========================================================= */

function levenshtein(a, b) {

    if (a === b) return 0;

    if (!a.length) return b.length;

    if (!b.length) return a.length;

    const matrix = [];

    for (let i = 0; i <= b.length; i++) {

        matrix[i] = [i];

    }

    for (let j = 0; j <= a.length; j++) {

        matrix[0][j] = j;

    }

    for (let i = 1; i <= b.length; i++) {

        for (let j = 1; j <= a.length; j++) {

            if (b.charAt(i - 1) === a.charAt(j - 1)) {

                matrix[i][j] =
                    matrix[i - 1][j - 1];

            } else {

                matrix[i][j] =
                    Math.min(

                        matrix[i - 1][j] + 1,

                        matrix[i][j - 1] + 1,

                        matrix[i - 1][j - 1] + 1

                    );

            }

        }

    }

    return matrix[b.length][a.length];

}


/* =========================================================
   SCORE RESULT
========================================================= */

function scoreSearchResult(page, query) {

    const normalizedQuery =
        normalizeSearchText(query);

    const queryWords =
        normalizedQuery.split(" ");

    const title =
        normalizeSearchText(page.title);

    const category =
        normalizeSearchText(page.category);

    const keywords =
        page.keywords.map(normalizeSearchText);

    const description =
        normalizeSearchText(page.description);

    let score = 0;


    /* Exact title */

    if (title === normalizedQuery) {

        score += 1000;

    }


    /* Title contains query */

    if (title.includes(normalizedQuery)) {

        score += 700;

    }


    /* Category */

    if (category.includes(normalizedQuery)) {

        score += 500;

    }


    /* Keyword exact match */

    keywords.forEach(keyword => {

        if (keyword === normalizedQuery) {

            score += 600;

        }

        if (keyword.includes(normalizedQuery)) {

            score += 300;

        }

    });


    /* Description */

    if (description.includes(normalizedQuery)) {

        score += 100;

    }


    /* Individual words */

    queryWords.forEach(word => {

        if (word.length < 2) return;


        if (title.includes(word)) {

            score += 250;

        }


        if (category.includes(word)) {

            score += 150;

        }


        keywords.forEach(keyword => {

            if (keyword.includes(word)) {

                score += 180;

            }

        });


        if (description.includes(word)) {

            score += 60;

        }

    });


    /* Small spelling mistakes */

    const titleWords =
        title.split(" ");

    queryWords.forEach(queryWord => {

        titleWords.forEach(titleWord => {

            if (
                queryWord.length >= 4 &&
                titleWord.length >= 4
            ) {

                const distance =
                    levenshtein(
                        queryWord,
                        titleWord
                    );

                if (distance === 1) {

                    score += 120;

                }

                if (
                    distance === 2 &&
                    queryWord.length >= 6
                ) {

                    score += 60;

                }

            }

        });

    });


    return score;

}


/* =========================================================
   SEARCH
========================================================= */

function searchOrbonix(query) {

    query =
        normalizeSearchText(query);

    if (!query) {

        return [];

    }


    return ORBONIX_PAGES

        .map(page => {

            return {

                ...page,

                score:
                    scoreSearchResult(
                        page,
                        query
                    )

            };

        })

        .filter(page => page.score > 0)

        .sort(
            (a, b) =>
                b.score - a.score
        )

        .slice(0, 12);

}


